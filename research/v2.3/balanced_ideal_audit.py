"""Balanced-order-ideal reduction of original-half chronology.

Mathematical claim (all n):
For any successful schedule of distinct undirected contacts, define P on
contact events from the original order of pairs of events sharing a vertex.
Every linear extension of P has exactly the same event set and final
information state. Any order ideal I of P with |I| = n-2 extends to a
permitted chronology having I as its original first half.

Therefore (not a novel classical priority claim):
  exists a bad successful original-half chronology in this poset
  <=> exists a balanced order ideal I with a cycle in both I and its
       complement.
This is an exact search reduction: examine balanced ideals, not every
permutation/linear extension. It does NOT solve quantification across all
admissible kernels, fringe attachments, and event posets.

Computational regression: the 12-event W8 poset has 6 balanced ideals,
whereas it has 51,200 linear extensions; the three cycle-rank
categories have 2 ideals each.
"""
from collections import Counter
from itertools import combinations
from pathlib import Path
import sys

BASE=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(BASE/"v1.5"))
from minimal_order_bridge import W8,gossip,cyclerank,extensions,extend_to,incident_orders,poset,kernel,edge

def poset_preds(schedule,n):
    """Transitive predecessor masks generated by local incident order."""
    last=[-1]*n
    deps=[]
    for i,(a,b) in enumerate(schedule):
        mask=0
        for v in (a,b):
            if last[v]>=0:
                p=last[v]
                mask|=(1<<p)|deps[p]
        deps.append(mask)
        last[a]=last[b]=i
    return deps

def balanced_ideals(schedule,n):
    m=len(schedule)
    assert m==2*n-4
    size=n-2
    pred=poset_preds(schedule,n)
    hist=Counter()
    sample={}
    for chosen in combinations(range(m),size):
        mask=sum(1<<i for i in chosen)
        if any((mask>>j&1) and ((pred[j]&mask)!=pred[j]) for j in chosen):
            continue
        a=cyclerank(n,[schedule[j] for j in chosen])
        b=cyclerank(n,[schedule[j] for j in range(m) if not mask>>j&1])
        hist[(a,b)]+=1
        sample.setdefault((a,b),chosen)
    return hist,sample

def main():
    assert gossip(8,W8)
    ideals,rep=balanced_ideals(W8,8)
    linear_hist,linrep,count=extensions(8,W8)
    assert count==51200
    assert ideals=={(0,0):2,(0,1):2,(1,0):2},ideals
    assert dict(linear_hist)=={(0,0):12800,(0,1):19200,(1,0):19200}
    assert not any(a>0 and b>0 for a,b in ideals)
    print("PASS W8 6 balanced ideals vs 51200 complete"
          " linear extensions; three types with 2 ideals each",flush=True)
    print("PASS ideal classes",dict(sorted(ideals.items())),flush=True)
    # The SAME abstract full event-poset has extensions with different
    # original midpoint ranks; the poset does not force unique ranks,
    # though all balanced ideals satisfy at least one forest.
    A=linrep[(0,1)];B=linrep[(0,0)]
    for n in range(8,18):
        a=extend_to(A,n);b=extend_to(B,n)
        assert gossip(n,a) and gossip(n,b)
        assert len({edge(e) for e in a})==2*n-4
        assert len({edge(e) for e in b})==2*n-4
        assert incident_orders(n,a)==incident_orders(n,b)
        assert poset(a)==poset(b)
        assert kernel(n,a)==kernel(n,b)
        half=n-2
        assert (cyclerank(n,a[:half]),cyclerank(n,a[half:]))==(0,1)
        assert (cyclerank(n,b[:half]),cyclerank(n,b[half:]))==(0,0)
    print("PASS same-event-poset midpoint rank non-determinacy"
          " example extended through n17",flush=True)
    print("LIMIT: a necessary-and-sufficient ideal TEST for each fully"
          " specified realizable event-poset, NOT a complete classification"
          " of all historical kernel families.",flush=True)

if __name__=="__main__":main()
